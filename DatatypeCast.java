package practice;

public class DatatypeCast {
	public static void main(String[] args) {
		byte b=100;
		short s=12345;
		int i=b;
		System.out.println(i);
		i=s;
		System.out.println(i);
		int i2=10000345;
		i=i2;
		System.out.println(i2);                                                                                                                                     
	}

}
